const DICTS: Record<Lang, Dict> = { en, pcm, ha, yo, ig };

export function t(lang: Lang | string, key: string, vars: Record<string, string | number> = {}): string {
  const d = DICTS[(lang as Lang)] ?? en;
  const s = d[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}
export const isLang = (x: string): x is Lang => (LANGS as string[]).includes(x);
